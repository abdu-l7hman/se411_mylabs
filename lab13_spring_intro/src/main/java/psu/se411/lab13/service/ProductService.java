package psu.se411.lab13.service;

import java.util.Optional;

import org.springframework.stereotype.Service;

import psu.se411.lab13.model.Product;
import psu.se411.lab13.repository.ProductRepository;

/** Business logic layer between the controller and the repository. */
@Service
public class ProductService {

	private final ProductRepository productRepository;

	public ProductService(ProductRepository productRepository) {
		this.productRepository = productRepository;
	}

	public Iterable<Product> findAll() {
		return productRepository.findAll();
	}

	public Optional<Product> findById(Integer id) {
		return productRepository.findById(id);
	}

	public Product create(Product product) {
		// the id is generated by the database, ignore any id sent by the client
		Product toSave = new Product(null, product.name(), product.description(), product.price());
		return productRepository.save(toSave);
	}
}
